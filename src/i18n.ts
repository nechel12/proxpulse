export function translate(
  lang: Lang,
  key: string,
  params?: Record<string, string | number>,
): string {
  let s = I18N[lang][key] ?? I18N.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
